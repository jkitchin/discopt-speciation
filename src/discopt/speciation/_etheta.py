def _chebval(u, c):
    # Clenshaw recurrence (same algorithm as numpy.polynomial.chebyshev.chebval)
    u2 = 2.0 * u
    c0, c1 = c[-2], c[-1]
    for i in range(3, len(c) + 1):
        c0, c1 = c[-i] - c1, c0 + c1 * u2
    return c0 + c1 * u


def _cheb2poly(c):
    # monomial coefficients (lowest order first) of sum_k c_k T_k(u)
    out = [0.0] * len(c)
    t_prev, t_cur = [1.0], [0.0, 1.0]
    for k, ck in enumerate(c):
        tk = t_prev if k == 0 else t_cur
        for i, v in enumerate(tk):
            out[i] += ck * v
        if k >= 1:
            t_next = [0.0] + [2.0 * v for v in t_cur]
            for i, v in enumerate(t_prev):
                t_next[i] -= v
            t_prev, t_cur = t_cur, t_next
    return tuple(out)


_POLY = {id(COEF): _cheb2poly(COEF), id(DCOEF): _cheb2poly(DCOEF)}


def _series(u, c):
    # Clenshaw uses each partial value twice per step, which makes an unshared
    # expression tree grow exponentially with the degree. Horner on the monomial
    # form references u once per step (error ~1e-11 for J, ~1e-9 for x J').
    if isinstance(u, (int, float)):
        return _chebval(u, c)
    p = _POLY[id(c)]
    acc = p[-1]
    for a in p[-2::-1]:
        acc = acc * u + a
    return acc


def J_and_xJprime(x):
    """``(J(x), x J'(x))`` for ``x > 0``; works for floats and discopt expressions."""
    t = (x * (1.0 / XC)) ** POWER
    u = 2.0 * t / (1.0 + t) - 1.0
    J = 0.25 * x - 1.0 + _series(u, COEF)
    xJp = 0.25 * x + _series(u, DCOEF) * (2.0 * POWER) * t / ((1.0 + t) * (1.0 + t))
    return J, xJp
